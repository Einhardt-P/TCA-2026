export function criarMapa(posicoesY) {
    let mapaX = []
    for (let y = 0; y < posicoesY.length; y++) {
        let mapaY = []
        for (let x = 0; x < posicoesY[y].length; x++) {
            if (mapaY < posicoesY[y].length) {
                mapaX.push(posicoesY[y][x])
            } else {
                mapaY.push(mapaX)
            }
        }
    }
    return mapaX;
}
